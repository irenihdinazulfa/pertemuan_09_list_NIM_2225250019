# Input: List angka nilai dengan 6 elemen
nilai = [75, 80, 65, 90, 88, 70]

# Proses: Mengakses elemen list berdasarkan indeks tertentu (0, -1) dan melakukan slicing (:3, 1:4)

# Output: Menampilkan elemen pertama, elemen terakhir, tiga elemen awal, dan elemen dari indeks 1 hingga 3
print(nilai[0])
print(nilai[-1])
print(nilai[:3])
print(nilai[1:4])